import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { hash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname } from "node:path";

import { z } from "zod";

import { profilePlan } from "../examples/profile-plan.ts";
import metadata from "../package.json" with { type: "json" };
import { architectureMermaid } from "../site/src/lib/architecture.ts";
import { WorkspaceSyncPolicySchema } from "../src/configuration.ts";

const ROOT = new URL("../", import.meta.url);
const SITE = new URL(metadata.homepage);
const REPOSITORY = metadata.repository.url
  .replace(/^git\+/u, "")
  .replace(/\.git$/u, "");
const ARCHIVE_NAME = `${metadata.name.replace(/^@/u, "").replaceAll("/", "-")}-${metadata.version}.tgz`;
const INSTALL = `pnpm add ${REPOSITORY}/releases/download/v${metadata.version}/${ARCHIVE_NAME} zod@${metadata.dependencies.zod}`;
const read = (path: string): Promise<string> =>
  readFile(new URL(path, ROOT), "utf8");
const source = await read("src/configuration.ts");
const overview =
  /^\/\*\*\n([\s\S]*?)\*\//u
    .exec(source)?.[1]
    ?.split("\n")
    .map((line) => line.replace(/^ \* ?/u, "").trimEnd())
    .join("\n")
    .trim() ?? "";
assert.ok(overview, "The policy contract must document its trust boundary");
const policyExample = await read("examples/policy.example.json");
WorkspaceSyncPolicySchema.parse(JSON.parse(policyExample));
const publicExample = async (path: string): Promise<string> => {
  const exampleSource = await read(path);
  return exampleSource
    .replaceAll(/^[ \t]*\/\/ eslint-disable-next-line [^\n]*\n/gmu, "")
    .replaceAll("../src/configuration.ts", () => metadata.name)
    .replaceAll("../src/", () => `${metadata.name}/`)
    .replaceAll(/\.ts(['"])/gu, "$1")
    .trim();
};
const example = await publicExample("examples/audit-directory.ts");
const planExample = await publicExample("examples/plan-and-apply.ts");
const policySchema = z.toJSONSchema(WorkspaceSyncPolicySchema, { io: "input" });
const modules = await Promise.all(
  Object.entries(metadata.exports).flatMap(([name, target]) => {
    // eslint-disable-next-line @sarj/no-runtime-typeof -- Export maps admit path strings and descriptor objects.
    if (typeof target === "string") return [];
    assert.match(target.types, /^\.\/dist\/[\w/-]+\.d\.ts$/u);
    assert.match(target.import, /^\.\/dist\/[\w/-]+\.js$/u);
    const module = target.import.slice("./dist/".length, -".js".length);
    return [
      (async () => ({
        name:
          name === "." ? metadata.name : `${metadata.name}/${name.slice(2)}`,
        module,
        declaration: await read(target.types),
      }))(),
    ];
  }),
);
const development =
  "mise install\nmise exec -- pnpm install --frozen-lockfile\nmise exec -- pnpm verify";
const notice = "<!-- Generated by scripts/documentation.ts. -->";
const readme = `${notice}
# Workspace Sync

${metadata.description}.

[Documentation](${SITE.href}) · [Plan / apply](${new URL("plan-and-apply/", SITE).href}) · [API](${new URL("api/", SITE).href})

Node.js ${metadata.engines.node}:

\`\`\`sh
${INSTALL}
\`\`\`

Start with the [read-only example](${new URL("configuration/", SITE).href}).
Use one immutable policy per process or Worker isolate. The host owns credentials,
approval and persistence; see [Security](SECURITY.md).

## Development

\`\`\`sh
${development}
\`\`\`

Run \`pnpm docs:generate\` after changing source, schemas or examples.

${metadata.license} · [Third-party notices](THIRD_PARTY_NOTICES.md)
`;
const security = `${notice}
# Security

Report vulnerabilities through [private advisories](${REPOSITORY}/security/advisories/new)
with the affected version and a synthetic reproduction. Keep credentials and
employee data out of public issues. Supported series: ${metadata.version.split(".").slice(0, 2).join(".")}.

${overview
  .split(/\n\s*\n/u)
  .slice(1)
  .join("\n\n")}
`;
const fontLicense = await read("LICENSES/Nunito-OFL-1.1.txt");
const fontCopyright = fontLicense.split("\n")[0] ?? "";
assert.ok(fontCopyright.startsWith("Copyright"));
const notices = `${notice}
# Third-party notices

The embedded Nunito Regular and Semibold font data in
\`src/org-sync/org-chart-fonts.ts\` retains its
[SIL Open Font License 1.1](LICENSES/Nunito-OFL-1.1.txt).
The code's ${metadata.license} license does not replace the font license.

${fontCopyright.replaceAll(/\((https?:[^)]+)\)/gu, "(<$1>)")}
`;
const outputs = new Map([
  ["README.md", readme],
  ["SECURITY.md", security],
  ["THIRD_PARTY_NOTICES.md", notices],
]);
await Promise.all(
  [...outputs].map(async ([path, content]) => {
    const formatted = execFileSync(
      "pnpm",
      ["exec", "oxfmt", `--stdin-filepath=${path}`],
      { cwd: ROOT, input: content, encoding: "utf8" },
    );
    if (process.argv.includes("--check"))
      assert.equal(
        await read(path),
        formatted,
        `${path} is stale; run pnpm docs:generate`,
      );
    else await writeFile(new URL(path, ROOT), formatted);
  }),
);

if (process.argv.includes("--site")) {
  assert.deepEqual(
    profilePlan.errors,
    [],
    "The documentation preview must be a valid plan",
  );
  const profile = profilePlan.profiles[0];
  assert.ok(profile, "The documentation preview must contain a profile");
  const reference = `${JSON.stringify({ version: metadata.version, modules, policySchema }, null, 2)}\n`;
  const generated = {
    version: metadata.version,
    node: metadata.engines.node,
    description: metadata.description,
    repository: REPOSITORY,
    install: INSTALL,
    example,
    planExample,
    policyExample,
    development,
    modules,
    preview: profile,
    security: overview.split(/\n\s*\n/u).slice(1),
  };
  const files = new Map([
    [
      "site/generated/reference.ts",
      `// Generated by scripts/documentation.ts.\nexport default ${JSON.stringify(generated, null, 2)} as const;\n`,
    ],
    ["site/public/generated/reference.json", reference],
    ["site/public/generated/policy.example.json", policyExample],
    [
      "site/public/generated/policy.schema.json",
      `${JSON.stringify(policySchema, null, 2)}\n`,
    ],
    ["site/public/generated/architecture.mmd", architectureMermaid()],
    ["site/public/generated/Nunito-OFL-1.1.txt", fontLicense],
    [
      "site/public/generated/health.json",
      `${JSON.stringify({ sourceHead: execFileSync("git", ["rev-parse", "HEAD"], { cwd: ROOT, encoding: "utf8" }).trim(), version: metadata.version, referenceSha256: hash("sha256", reference) })}\n`,
    ],
  ]);
  await Promise.all(
    [...files].map(async ([path, content]) => {
      const destination = new URL(path, ROOT);
      await mkdir(dirname(destination.pathname), { recursive: true });
      await writeFile(destination, content);
    }),
  );
  process.stdout.write(`Generated ${String(modules.length)} API modules.\n`);
}
