const fontLicense = await read("LICENSES/Nunito-OFL-1.1.txt");
const fontCopyright = fontLicense.split("\n")[0] ?? "";
assert.ok(fontCopyright.startsWith("Copyright"));
const notices = `${notice}
# Third-party notices

The embedded Nunito Regular and Semibold font data in
\`src/org-sync/org-chart-fonts.ts\` retains its
[SIL Open Font License 1.1](LICENSES/Nunito-OFL-1.1.txt).
The code's ${metadata.license} license does not replace the font license.

${fontCopyright.replaceAll(/\((https?:[^)]+)\)/gu, "(<$1>)")}
`;
