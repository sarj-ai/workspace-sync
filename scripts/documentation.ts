import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { hash } from "node:crypto";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname } from "node:path";

import { z } from "zod";

import metadata from "../package.json" with { type: "json" };
import { WorkspaceSyncPolicySchema } from "../src/configuration.ts";

const ROOT = new URL("../", import.meta.url);
const SITE = new URL(metadata.homepage);
const REPOSITORY = metadata.repository.url
  .replace(/^git\+/u, "")
  .replace(/\.git$/u, "");
const ARCHIVE_NAME = `${metadata.name.replace(/^@/u, "").replaceAll("/", "-")}-${metadata.version}.tgz`;
const INSTALL = `pnpm add ${REPOSITORY}/releases/download/v${metadata.version}/${ARCHIVE_NAME}`;
const read = (path: string): Promise<string> =>
  readFile(new URL(path, ROOT), "utf8");
const source = await read("src/configuration.ts");
const overview =
  /^\/\*\*\n([\s\S]*?)\*\//u
    .exec(source)?.[1]
    ?.split("\n")
    .map((line) => line.replace(/^ \* ?/u, "").trimEnd())
    .join("\n")
    .trim() ?? "";
assert.ok(
  overview,
  "The package overview must live next to the policy contract",
);
const policyExample = await read("examples/policy.example.json");
WorkspaceSyncPolicySchema.parse(JSON.parse(policyExample));
const exampleSource = await read("examples/audit-directory.ts");
const example = exampleSource
  .replaceAll(/^[ \t]*\/\/ eslint-disable-next-line [^\n]*\n/gmu, "")
  .replaceAll("../src/configuration.ts", () => metadata.name)
  .replaceAll("../src/", () => `${metadata.name}/`)
  .replaceAll(/\.ts(['"])/gu, "$1");
const policySchema = z.toJSONSchema(WorkspaceSyncPolicySchema, { io: "input" });
const modules = await Promise.all(
  Object.entries(metadata.exports).flatMap(([name, target]) => {
    // eslint-disable-next-line @sarj/no-runtime-typeof -- Export maps admit both path strings and descriptor objects.
    if (typeof target === "string") return [];
    assert.match(target.types, /^\.\/dist\/[\w/-]+\.d\.ts$/u);
    assert.match(target.import, /^\.\/dist\/[\w/-]+\.js$/u);
    const module = target.import.slice("./dist/".length, -".js".length);
    assert.match(module, /^[\w/-]+$/u);
    return [
      (async () => ({
        name:
          name === "." ? metadata.name : `${metadata.name}/${name.slice(2)}`,
        module,
        declaration: await read(target.types),
      }))(),
    ];
  }),
);

function html(value: string): string {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

function overviewParagraphs(): string {
  return overview
    .split(/\n\s*\n/u)
    .map((paragraph) => `<p>${html(paragraph.replaceAll("\n", " "))}</p>`)
    .join("\n");
}

function code(value: string): string {
  return `<pre tabindex="0"><code>${html(value.trim())}</code></pre>`;
}

function page(title: string, path: string, body: string): string {
  const fullTitle =
    title === "Workspace Sync" ? title : `${title} · Workspace Sync`;
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>${html(fullTitle)}</title><meta name="description" content="${html(metadata.description)}">
<link rel="canonical" href="${new URL(path, SITE).href}"><link rel="stylesheet" href="${SITE.pathname}style.css"></head>
<body><a class="skip" href="#main">Skip to content</a>
<header><nav aria-label="Main"><a class="brand" href="/">Sarj Engineering</a><a href="${SITE.pathname}">Workspace Sync</a><a href="${SITE.pathname}api/">API</a><a href="${SITE.pathname}configuration/">Configuration</a><a href="${SITE.pathname}development/">Development</a><a href="${REPOSITORY}">GitHub ↗</a></nav></header>
<main id="main"><p class="eyebrow">Workspace Sync · ${html(metadata.version)}</p><h1>${html(title)}</h1>${body}</main>
<footer>Derived from source declarations, schemas and executable examples. <a href="${REPOSITORY}/blob/main/LICENSE">${html(metadata.license)} license</a> · <a href="${SITE.pathname}security/">Security</a></footer></body></html>\n`;
}

