import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { hash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname } from "node:path";

import metadata from "../package.json" with { type: "json" };
import { architectureMermaid } from "../site/src/lib/architecture.ts";
import { deriveDocumentationReference } from "./derive-documentation-reference.ts";

const ROOT = new URL("../", import.meta.url);
const SITE = new URL(metadata.homepage);
const {
  development,
  install,
  modules,
  policyExample,
  policySchema,
  repository,
  security,
} = await deriveDocumentationReference(ROOT);
const read = (path: string): Promise<string> =>
  readFile(new URL(path, ROOT), "utf8");
const notice = "<!-- Generated by scripts/documentation.ts. -->";
const readme = `${notice}
# Workspace Sync

${metadata.description}.

[Documentation](${SITE.href}) · [Plan / apply](${new URL("plan-and-apply/", SITE).href}) · [API](${new URL("api/", SITE).href})

Node.js ${metadata.engines.node}:

\`\`\`sh
${install}
\`\`\`

Start with the [read-only example](${new URL("configuration/", SITE).href}).
Use one immutable policy per process or Worker isolate. The host owns credentials,
approval and persistence; see [Security](SECURITY.md).

## Development

\`\`\`sh
${development}
\`\`\`

Run \`pnpm docs:generate\` after changing source, schemas or examples.

${metadata.license} · [Third-party notices](THIRD_PARTY_NOTICES.md)
`;
const securityPolicy = `${notice}
# Security

Report vulnerabilities through [private advisories](${repository}/security/advisories/new)
with the affected version and a synthetic reproduction. Keep credentials and
employee data out of public issues. Supported series: ${metadata.version.split(".").slice(0, 2).join(".")}.

${security.join("\n\n")}
`;
const fontLicense = await read("LICENSES/Nunito-OFL-1.1.txt");
const fontCopyright = fontLicense.split("\n")[0] ?? "";
assert.ok(fontCopyright.startsWith("Copyright"));
const notices = `${notice}
# Third-party notices

The embedded Nunito Regular and Semibold font data in
\`src/org-sync/org-chart-fonts.ts\` retains its
[SIL Open Font License 1.1](LICENSES/Nunito-OFL-1.1.txt).
The code's ${metadata.license} license does not replace the font license.

${fontCopyright.replaceAll(/\((https?:[^)]+)\)/gu, "(<$1>)")}
`;
const outputs = new Map([
  ["README.md", readme],
  ["SECURITY.md", securityPolicy],
  ["THIRD_PARTY_NOTICES.md", notices],
]);
await Promise.all(
  [...outputs].map(async ([path, content]) => {
    const formatted = execFileSync(
      "pnpm",
      ["exec", "oxfmt", `--stdin-filepath=${path}`],
      { cwd: ROOT, input: content, encoding: "utf8" },
    );
    if (process.argv.includes("--check"))
      assert.equal(
        await read(path),
        formatted,
        `${path} is stale; run pnpm docs:generate`,
      );
    else await writeFile(new URL(path, ROOT), formatted);
  }),
);

if (process.argv.includes("--site")) {
  const reference = `${JSON.stringify({ version: metadata.version, modules, policySchema }, null, 2)}\n`;
  const files = new Map([
    ["site/public/generated/reference.json", reference],
    ["site/public/generated/policy.example.json", policyExample],
    [
      "site/public/generated/policy.schema.json",
      `${JSON.stringify(policySchema, null, 2)}\n`,
    ],
    ["site/public/generated/architecture.mmd", architectureMermaid()],
    ["site/public/generated/Nunito-OFL-1.1.txt", fontLicense],
    [
      "site/public/generated/health.json",
      `${JSON.stringify({ sourceHead: execFileSync("git", ["rev-parse", "HEAD"], { cwd: ROOT, encoding: "utf8" }).trim(), version: metadata.version, referenceSha256: hash("sha256", reference) })}\n`,
    ],
  ]);
  await Promise.all(
    [...files].map(async ([path, content]) => {
      const destination = new URL(path, ROOT);
      await mkdir(dirname(destination.pathname), { recursive: true });
      await writeFile(destination, content);
    }),
  );
  process.stdout.write(`Generated ${String(modules.length)} API modules.\n`);
}
